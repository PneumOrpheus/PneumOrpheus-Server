@dataclass
class InferenceInput:
    analysis_id: str
    patient_id: str
    patient_name: str
    modality: str
    clinician_email: str
    file_name: str
    file_mime_type: str
    file_size_bytes: int
    file_bytes: bytes


class InferenceService:
    def __init__(self) -> None:
        self.settings = get_settings()
        self.model_store = ModelStore()
        self.segmentation_runtime = SegmentationRuntime()

    def run(self, payload: InferenceInput) -> InferenceResponse:
        model_name = self.settings.default_model_name
        model_version = self.settings.default_model_version
        try:
            tumor_mask = self.segmentation_runtime.segment(payload.file_bytes)
            model_path = self.model_store.resolve_model_path(model_name=model_name, model_version=model_version)
            runtime = ModelRuntime(model_path=model_path)
            runtime_result = runtime.run(
                file_bytes=payload.file_bytes,
                modality=payload.modality,
                tumor_mask=tumor_mask,
            )
        except Exception as error:
            raise InferenceServiceError(str(error)) from error

        predicted_type = str(runtime_result.get("predicted_type") or "Unknown")
        predicted_index: int = int(runtime_result.get("predicted_index") or 0)
        confidence = float(runtime_result.get("confidence") or 0.0)
        confidence = max(0.0, min(1.0, confidence))
        reasoning = str(runtime_result.get("reasoning") or "Prediction generated by model runtime.")

        all_class_probs: dict[str, float] = runtime_result.get("all_class_probs") or {}
        seg_mask: np.ndarray | None = runtime_result.get("seg_mask")
        seg_per_instance: np.ndarray | None = runtime_result.get("seg_per_instance")
        bbox: np.ndarray | None = runtime_result.get("bbox")

        # TNM staging (IASLC 9th edition, 2025), sized off the real tumour segmentation mask.
        tnm = derive_tnm(
            predicted_type=predicted_type,
            confidence=confidence,
            tumor_mask_3d=tumor_mask,
        )
        proposed_tnm = tnm["tnm_string"]

        # GradCAM++ visualization data
        gradcam_data = runtime.compute_gradcam(class_idx=predicted_index)

        # Build segmentation data payload
        segmentation_data: dict[str, Any] = {
            "tnmDetail": {
                "t":                   tnm["t"],
                "n":                   tnm["n"],
                "m":                   tnm["m"],
                "tnmString":           tnm["tnm_string"],
                "bestCaseStage":       tnm["best_case_stage"],
                "estimatedDiameterMm": tnm["estimated_diameter_mm"],
                "sizeMethod":          tnm["size_method"],
                "caveats":             tnm["caveats"],
                "edition":             tnm["edition"],
            },
        }

        if seg_mask is not None:
            # Downsample to 64×64 to keep the JSON payload manageable
            mask_small = _resize_mask(seg_mask, target=64)
            segmentation_data["segMask"] = {
                "data": mask_small.tolist(),
                "shape": list(mask_small.shape),
                "description": "Averaged per-instance sigmoid segmentation probability map",
            }

        if bbox is not None and len(bbox) >= 4:
            segmentation_data["boundingBox"] = {
                "xMin": round(float(bbox[0]), 4),
                "yMin": round(float(bbox[1]), 4),
                "xMax": round(float(bbox[2]), 4),
                "yMax": round(float(bbox[3]), 4),
                "description": "Averaged normalised bounding box [0,1] from detection head",
            }

        if all_class_probs:
            segmentation_data["classProbs"] = {
                k: round(float(v), 4) for k, v in all_class_probs.items()
            }

        # Three MIL visualizations (plain CT / seg overlay / GradCAM++)
        three_vis = build_three_visualizations(
            input_tensor=runtime._last_input_tensor,
            seg_per_instance=seg_per_instance,
            gradcam_data=gradcam_data,
        )
        if three_vis:
            segmentation_data["plainCt"] = three_vis["plainCt"]
            segmentation_data["segmentationOverlay"] = three_vis["segmentationOverlay"]
            segmentation_data["gradCamOverlay"] = three_vis["gradCamOverlay"]
            # pneumorpheus-app only recognises a single `segmentationData.visualization`
            # block (legacy shape); alias the segmentation-overlay variant into it so
            # the app's slice viewer actually has something to render.
            segmentation_data["visualization"] = _to_app_visualization(three_vis["segmentationOverlay"])
        else:
            # Fallback: single NIfTI visualization for non-MIL inputs
            visualization = build_nifti_visualization(
                file_name=payload.file_name,
                file_bytes=payload.file_bytes,
                runtime_result=runtime_result,
            )
            if visualization:
                segmentation_data["visualization"] = visualization

        nifti_files = _build_nifti_files(
            ct_volume=runtime._last_ct_volume,
            ct_affine=runtime._last_ct_affine,
            mil_indices=runtime._last_mil_indices,
            tumor_mask=tumor_mask,
            seg_ct_volume=self.segmentation_runtime.get_last_ct_volume(),
            seg_affine=self.segmentation_runtime.get_last_affine(),
            gradcam_data=gradcam_data,
        )
        if nifti_files:
            segmentation_data["niftiFiles"] = nifti_files

        findings = _build_findings(predicted_type, confidence, bbox, tnm)
        left_cls, right_cls = _build_classifications(predicted_type, confidence, all_class_probs, bbox)

        return InferenceResponse(
            analysisId=payload.analysis_id,
            patientId=payload.patient_id,
            patientName=payload.patient_name,
            modality=payload.modality,
            clinicianEmail=payload.clinician_email,
            receivedAt=datetime.now(timezone.utc).isoformat(),
            sourceFile=SourceFileMetadata(
                name=payload.file_name,
                mimeType=payload.file_mime_type,
                sizeBytes=payload.file_size_bytes,
            ),
            findings=findings,
            cancerType=predicted_type,
            classificationConfidence=confidence,
            reasoning=reasoning,
            proposedTnmStage=proposed_tnm,
            classifications=[left_cls, right_cls],
            segmentationData=segmentation_data,
            modelInfo={
                "modelName":    model_name,
                "modelVersion": model_version,
                "modelSource":  self.settings.model_source,
                "modelPath":    str(model_path),
            },
        )


