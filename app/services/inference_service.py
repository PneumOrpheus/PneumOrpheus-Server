def _build_nifti_files(
    ct_volume: np.ndarray | None,
    ct_affine: np.ndarray | None,
    mil_indices: np.ndarray | None,
    tumor_mask: np.ndarray | None,
    seg_ct_volume: np.ndarray | None,
    seg_affine: np.ndarray | None,
    gradcam_data: tuple[np.ndarray, np.ndarray] | None,
) -> dict[str, Any]:
    files: dict[str, Any] = {}

    if ct_volume is not None and ct_affine is not None:
        files["plainCt"] = build_nifti_file_payload(ct_volume, ct_affine, "plain_ct.nii.gz")

    if tumor_mask is not None and seg_affine is not None and seg_ct_volume is not None:
        try:
            rgb = build_segmentation_overlay_volume(seg_ct_volume, tumor_mask)
            files["segmentationRoi"] = build_rgb_nifti_file_payload(rgb, seg_affine, "segmentation_roi.nii.gz")
        except Exception:
            pass

    if (
        gradcam_data is not None
        and ct_volume is not None
        and ct_affine is not None
        and mil_indices is not None
    ):
        try:
            cam_np, _att_np = gradcam_data
            rgb = build_gradcam_overlay_volume(ct_volume, cam_np, mil_indices)
            files["gradCam"] = build_rgb_nifti_file_payload(rgb, ct_affine, "grad_cam.nii.gz")
        except Exception:
            pass

    return files


def _to_app_visualization(vis: dict[str, Any]) -> dict[str, Any]:
    """Remap a slice-overlay-v1 block's per-slice keys to what pneumorpheus-app's
    AnalysisVisualization component reads (hasOverlay/overlayCoverage instead of
    this server's own hasMask/maskCoverage naming).
    """
    return {
        **vis,
        "slices": [
            {
                **slice_item,
                "hasOverlay": slice_item.get("hasMask", False),
                "overlayCoverage": slice_item.get("maskCoverage", 0.0),
            }
            for slice_item in vis.get("slices", [])
        ],
    }


def _bbox_x_center(bbox: np.ndarray | None) -> float | None:
    """Return normalised x-centre of the bounding box, or None."""
    if bbox is None or len(bbox) < 4:
        return None
    return float((bbox[0] + bbox[2]) / 2.0)


def _build_findings(
    predicted_type: str,
    confidence: float,
    bbox: np.ndarray | None,
    tnm: dict,
) -> str:
    pct = round(confidence * 100)
    text = f"Model predicts {predicted_type} with {pct}% confidence"

    x_center = _bbox_x_center(bbox)
    if x_center is not None:
        side = "left" if x_center < 0.5 else "right"
        text += f". Primary lesion localised to the {side} lung"

    diam = tnm.get("estimated_diameter_mm")
    t_cat = tnm.get("t", "Tx")
    tnm_str = tnm.get("tnm_string", "")
    if diam is not None:
        text += f". Estimated tumour diameter ~{diam} mm ({t_cat})"
    if tnm_str:
        text += f". Staging: {tnm_str}"
        best = tnm.get("best_case_stage", "")
        if best:
            text += f" ({best})"

    text += ". Analysis based on CT morphology, density patterns, and multi-instance attention."
    return text


def _build_classifications(
    predicted_type: str,
    confidence: float,
    all_class_probs: dict[str, float],
    bbox: np.ndarray | None,
) -> tuple[ClassificationItem, ClassificationItem]:
    x_center = _bbox_x_center(bbox)
    if x_center is None or x_center < 0.5:
        primary_side, secondary_side = "Left", "Right"
    else:
        primary_side, secondary_side = "Right", "Left"

    # Differential label for the secondary side
    if all_class_probs:
        others = sorted(
            ((k, v) for k, v in all_class_probs.items() if k != predicted_type),
            key=lambda kv: -kv[1],
        )
        secondary_label = others[0][0] if others else predicted_type
        secondary_conf  = max(0.0, min(1.0, others[0][1])) if others else max(0.0, confidence - 0.05)
    else:
        secondary_label = predicted_type
        secondary_conf  = max(0.0, confidence - 0.05)

    primary = ClassificationItem(
        side=primary_side,
        prediction=predicted_type,
        confidence=confidence,
        explanation=(
            f"Primary lesion detected in the {primary_side.lower()} lung with dominant "
            f"{predicted_type} signature ({round(confidence * 100)}% confidence)."
        ),
    )
    secondary = ClassificationItem(
        side=secondary_side,
        prediction=secondary_label,
        confidence=round(secondary_conf, 4),
        explanation=(
            f"Supporting radiographic evidence in the {secondary_side.lower()} hemi-thorax "
            f"suggests {secondary_label} ({round(secondary_conf * 100)}% confidence)."
        ),
    )
    return primary, secondary


def _resize_mask(mask: np.ndarray, target: int) -> np.ndarray:
    """Bilinear downsample a 2-D probability map to (target, target)."""
    try:
        import torch
        import torch.nn.functional as F

        t = torch.from_numpy(mask).float().unsqueeze(0).unsqueeze(0) # (1,1,H,W)
        t = F.interpolate(t, size=(target, target), mode="bilinear", align_corners=False)
        return t.squeeze().numpy()
    except Exception:
        # Fallback with nearest-neighbour via numpy slicing
        h, w = mask.shape
        step_h = max(1, h // target)
        step_w = max(1, w // target)
        return mask[::step_h, ::step_w][:target, :target]


